def load_env_file(filepath: str) -> Dict[str, str]:
    env_vars: Dict[str, str] = {}
    if not os.path.exists(filepath):
        return env_vars
    with open(filepath, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            env_vars[k.strip()] = v.strip()
    return env_vars


def call_gemini_api(api_key: str, model_id: str, system_prompt: str, user_prompt: str) -> Tuple[str | None, float, str]:
    """
    Calls Google Gemini REST API and returns (response_text, latency_ms, status_note).
    Tries candidate model IDs mirroring UnifiedLLMClient in src/system2/llmClient.ts.
    """
    candidates = [model_id, "gemini-2.5-flash", "gemini-2.0-flash", "gemini-1.5-flash"]
    seen = set()
    unique_models = [m for m in candidates if not (m in seen or seen.add(m))]

    t0 = time.perf_counter()
    last_err = "Unknown error"
    for mid in unique_models:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{mid}:generateContent?key={api_key}"
        payload = json.dumps({
            "systemInstruction": {"parts": [{"text": system_prompt}]},
            "contents": [{"role": "user", "parts": [{"text": user_prompt}]}],
            "generationConfig": {"responseMimeType": "application/json", "temperature": 0.1},
        }).encode("utf-8")
        req = urllib.request.Request(url, data=payload, headers={"Content-Type": "application/json"}, method="POST")
        try:
            with urllib.request.urlopen(req, timeout=8.0) as resp:
                raw = resp.read().decode("utf-8")
                dt_ms = (time.perf_counter() - t0) * 1000.0
                data = json.loads(raw)
                text = data.get("candidates", [{}])[0].get("content", {}).get("parts", [{}])[0].get("text")
                if text:
                    return text, dt_ms, f"OK ({mid})"
        except urllib.error.HTTPError as e:
            err_body = ""
            try:
                err_body = e.read().decode("utf-8")[:160]
            except Exception:
                pass
            last_err = f"HTTP {e.code} on {mid}: {err_body}"
        except Exception as e:
            last_err = f"{type(e).__name__}: {e}"

    dt_ms = (time.perf_counter() - t0) * 1000.0
    return None, dt_ms, last_err


def extract_json_object(text: str) -> Dict[str, Any] | None:
    if not text:
        return None
    cleaned = text.strip()
    if "```" in cleaned:
        parts = cleaned.split("```")
        for p in parts:
            p_strip = p.strip()
            if p_strip.startswith("json"):
                p_strip = p_strip[4:].strip()
            if p_strip.startswith("{") and "}" in p_strip:
                cleaned = p_strip
                break
    start = cleaned.find("{")
    end = cleaned.rfind("}")
    if start != -1 and end != -1 and end > start:
        candidate = cleaned[start : end + 1]
        try:
            return json.loads(candidate)
        except Exception:
            # Sanitize unescaped newlines inside string literals generated by code models
            sanitized = candidate.replace("\r\n", " ").replace("\n", " ")
            try:
                return json.loads(sanitized)
            except Exception:
                return None
    return None


def cpu_baseline_reflex_rule(voxels_np: np.ndarray, entities_np: np.ndarray, bot_np: np.ndarray) -> np.ndarray:
    """
    Baseline static single-rule reflex evaluator (mirrors simple hardcoded threshold rules
    that only inspect entity distance/creeper/lava without 3D voxel parkour or weapon-cooldown kiting).
    """
    out = np.zeros((9,), dtype=np.float32)
    # Check entity 0
    dist = entities_np[0, 6]
    is_hostile = entities_np[0, 7] > 0.5
    is_creeper = entities_np[0, 8] > 0.5
    if is_creeper and dist < 4.8:
        out[1] = 1.0  # move_back
        out[4] = 1.0  # jump
        out[5] = 1.0  # sprint
        out[8] = 1.0  # shield
    elif is_hostile and dist < 4.0:
        # Static rule attacks blindly without checking weapon cooldown or strafing arrows
        out[0] = 1.0
        out[7] = 1.0
    else:
        out[0] = 1.0
    return out


def cpu_iterative_chunk_scan(chunk_np: np.ndarray) -> Dict[str, Any]:
    """
    Simulates iterative CPU block-by-block scanning across a full 64x64x64 chunk (262,144 blocks)
    in Python/JS to find ore clusters, lava hazards, and flat pads.
    """
    D, H, W = chunk_np.shape
    ore_count = 0
    lava_count = 0
    ore_sum_x, ore_sum_y, ore_sum_z = 0, 0, 0
    for x in range(0, D):
        for y in range(0, H):
            for z in range(0, W):
                b = int(chunk_np[x, y, z])
                if b in (15, 16, 18, 20):
                    ore_count += 1
                    ore_sum_x += x
                    ore_sum_y += y
                    ore_sum_z += z
                elif b == 11:
                    lava_count += 1
    return {
        "ore_count": ore_count,
        "has_lava": lava_count > 0,
    }


